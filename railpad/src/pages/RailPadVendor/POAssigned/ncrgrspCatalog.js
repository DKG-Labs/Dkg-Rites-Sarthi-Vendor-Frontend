export const normalizeDwg = (dwg) => (dwg || '').replace(/^RDSO[\/-]/i, '').replace(/^(RT|T)[\/-]?/i, '').trim().toUpperCase();

export const resolveNcrgrspCatalogKey = (dwgOrType, candidateDrawings = []) => {
  if (!dwgOrType && (!candidateDrawings || candidateDrawings.length === 0)) {
    return 'RT-9790';
  }

  const str = String(dwgOrType || '').toLowerCase().trim();
  if (str.includes('4218_1') || str.includes('4218-1') || str.includes('4218_01') || str.includes('4218 (1)') || str.includes('4218 annexure')) {
    return 'RT-4218_1';
  }
  if (str.includes('4218')) {
    return 'RT-4218';
  }
  if (str.includes('4865')) {
    if (str.includes('52 kg') || str.includes('52kg') || str.includes('52')) {
      return 'RT-4865 (52 KG)';
    }
    if (str.includes('alt-8') || str.includes('alt 8') || str.includes('alt.8') || str.includes('alt08') || str.includes('alt-08')) {
      return 'RT-4865 Alt-8';
    }
    if (str.includes('alt-9') || str.includes('alt 9') || str.includes('alt.9') || str.includes('alt09') || str.includes('alt-09')) {
      return 'RT-4865 Alt-9';
    }
    return 'RT-4865 (52 KG)';
  }
  if (str.includes('5691-1') || str.includes('5691_1') || str.includes('5691 (1)') || str.includes('5691-01')) {
    return 'RT-5691-1';
  }
  if (str.includes('5693-1') || str.includes('5693_1') || str.includes('5693 (1)') || str.includes('5693-01')) {
    return 'RT-5693-1';
  }
  
  // 1. Direct key match
  if (NCRGRSP_CATALOG[dwgOrType]) return dwgOrType;

  // 2. Exact / normalized match on key names from dwgOrType
  const norm = normalizeDwg(dwgOrType);
  for (const key of Object.keys(NCRGRSP_CATALOG)) {
    const cleanKey = key.replace(/^(RT|T)[\/-]?/i, '').trim();
    if (
      normalizeDwg(key) === norm ||
      key.toLowerCase() === str ||
      str.includes(key.toLowerCase()) ||
      str.includes(cleanKey.toLowerCase())
    ) {
      return key;
    }
  }

  // 3. Search drawing numbers inside catalog items (Fallback when call drawing is not a main turnout key)
  const candidateList = Array.isArray(candidateDrawings) ? candidateDrawings.filter(Boolean) : [];
  if (candidateList.length > 0) {
    let bestKey = null;
    let maxMatches = 0;

    for (const [key, items] of Object.entries(NCRGRSP_CATALOG)) {
      const itemDwgSet = new Set(items.map(item => normalizeDwg(item.drawingNo)));
      let matchCount = 0;
      for (const cd of candidateList) {
        if (itemDwgSet.has(normalizeDwg(cd))) {
          matchCount++;
        }
      }
      if (matchCount > maxMatches) {
        maxMatches = matchCount;
        bestKey = key;
      }
    }

    if (bestKey && maxMatches > 0) {
      return bestKey;
    }
  }

  if (String(dwgOrType).includes('10.00mm') || String(dwgOrType).includes('10mm') || String(dwgOrType).includes('9790') || String(dwgOrType).includes('10093') || String(dwgOrType).includes('10114')) {
    return 'RT-9790';
  }

  return Object.keys(NCRGRSP_CATALOG)[0];
};
